export const recentResults = matches
  .filter((item) => item.status === "completed")
  .sort((a, b) => +new Date(b.scheduledAt) - +new Date(a.scheduledAt));

export const liveMatches = matches
  .filter((item) => item.status === "live")
  .sort((a, b) => +new Date(a.scheduledAt) - +new Date(b.scheduledAt));

export const scheduledMatches = matches
  .filter((item) => item.status === "scheduled")
  .sort((a, b) => +new Date(a.scheduledAt) - +new Date(b.scheduledAt));

export function getPlayerMatches(playerId: string) {
  return matches
    .filter(
      (item) =>
        item.side1.playerIds.includes(playerId) || item.side2.playerIds.includes(playerId),
    )
    .sort((a, b) => +new Date(b.scheduledAt) - +new Date(a.scheduledAt));
}

export function getTournamentMatches(tournamentId: string) {
  return matches
    .filter((item) => item.tournamentId === tournamentId)
    .sort((a, b) => +new Date(a.scheduledAt) - +new Date(b.scheduledAt));
}
