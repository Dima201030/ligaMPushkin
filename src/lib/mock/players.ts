export const playerById = new Map(players.map((item) => [item.id, item]));
export const playerBySlug = new Map(players.map((item) => [item.slug, item]));

export function getPlayer(id: string): Player {
  const found = playerById.get(id);
  if (!found) throw new Error(`Unknown player: ${id}`);
  return found;
}

export function getPlayerBySlug(slug: string): Player | undefined {
  return playerBySlug.get(slug);
}

export function playerLabel(id: string) {
  const item = playerById.get(id);
  return item ? `${item.firstName} ${item.lastName}` : "Неизвестный игрок";
}

